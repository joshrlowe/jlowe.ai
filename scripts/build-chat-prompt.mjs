#!/usr/bin/env node
/**
 * Emits the chat Lambda's persona guardrails → `services/chat/src/system-prompt.ts`.
 * Retrieved corpus chunks are appended per-request by the handler
 * (`formatContext`); do not bake project bodies into this file. Run by
 * `pnpm corpus` alongside build-corpus.mjs; CI regenerates + git-diffs both.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import matter from "gray-matter";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORPUS_DIR = join(ROOT, "corpus");
const OUT = join(ROOT, "services", "chat", "src", "system-prompt.ts");

// Persona bodies — read raw (not the corpus schema; persona isn't a corpus kind).
const personaDir = join(CORPUS_DIR, "persona");
const persona = existsSync(personaDir)
  ? readdirSync(personaDir)
      .sort()
      .filter((f) => f.endsWith(".md"))
      .map((f) =>
        matter(readFileSync(join(personaDir, f), "utf8")).content.trim(),
      )
      .join("\n\n")
  : "";

const module = `// GENERATED by scripts/build-chat-prompt.mjs — do not edit by hand.
// Source: corpus/persona/*.md (guardrails only). Retrieved context is appended
// per-request. Run \`pnpm corpus\`.

export const SYSTEM_PROMPT = ${JSON.stringify(persona)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, module);
console.log(`chat-prompt: persona → services/chat/src/system-prompt.ts`);
