#!/usr/bin/env node
/**
 * Emits the chat Lambda's grounding bundle from the corpus single-source-of-
 * truth → `services/chat/src/system-prompt.ts` (the persona guardrails + the
 * serialized public corpus). The whole corpus is small enough to live in the
 * system prompt, so the MVP twin needs no vector store. Run by `pnpm corpus`
 * alongside build-corpus.mjs; CI regenerates + git-diffs both for drift.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import matter from "gray-matter";

import { CorpusFrontmatter } from "./corpus-schema.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORPUS_DIR = join(ROOT, "corpus");
const OUT = join(ROOT, "services", "chat", "src", "system-prompt.ts");
const DIRS = ["projects", "articles", "faq"];

// Public corpus entries (same schema + public-only filter as build-corpus.mjs).
const entries = [];
for (const dir of DIRS) {
  const full = join(CORPUS_DIR, dir);
  if (!existsSync(full)) continue;
  for (const file of readdirSync(full).sort()) {
    if (!file.endsWith(".md")) continue;
    const { data, content } = matter(readFileSync(join(full, file), "utf8"));
    const parsed = CorpusFrontmatter.safeParse(data);
    if (!parsed.success) {
      console.error(`chat-prompt: ${dir}/${file} failed validation`);
      process.exit(1);
    }
    if (parsed.data.visibility !== "public") continue;
    entries.push({ ...parsed.data, body: content.trim() });
  }
}
entries.sort((a, b) => a.slug.localeCompare(b.slug));

// Persona bodies — read raw (not the corpus schema; persona isn't a corpus kind).
const personaDir = join(CORPUS_DIR, "persona");
const persona = existsSync(personaDir)
  ? readdirSync(personaDir)
      .sort()
      .filter((f) => f.endsWith(".md"))
      .map((f) =>
        matter(readFileSync(join(personaDir, f), "utf8")).content.trim(),
      )
      .join("\n\n")
  : "";

const corpusText = entries
  .map((e) => {
    const lines = [`## ${e.title}${e.role ? ` — ${e.role}` : ""}`];
    if (e.stack?.length) lines.push(`Stack: ${e.stack.join(", ")}`);
    if (e.outcomes?.length) lines.push(...e.outcomes.map((o) => `- ${o}`));
    lines.push("", e.body);
    return lines.join("\n");
  })
  .join("\n\n");

const systemPrompt = `${persona}\n\n---\n\n# CONTEXT — Josh's corpus (your only source of truth)\n\n${corpusText}`;

const module = `// GENERATED by scripts/build-chat-prompt.mjs — do not edit by hand.
// Source: corpus/persona/*.md + corpus/**/*.md (public). Run \`pnpm corpus\`.

export const SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, module);
console.log(
  `chat-prompt: persona + ${entries.length} corpus entries → services/chat/src/system-prompt.ts`,
);
